// Writes .github/dependabot.yml for the ecosystems this project really has (Dependabot reports an error for an ecosystem
// whose manifest is missing, so a fixed file would be wrong as soon as an app is added or removed).
//   deno task security:sync            write the file
//   deno task security:sync --check    exit 1 when the file is out of date (for CI or a pre-push habit)
// Run it again after `add-app`; `deno task setup` runs it too.
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

export interface Found {
  deno: string[];
  docker: string[];
  pub: string[];
  cargo: string[];
}

const SKIP = new Set([
  "node_modules",
  ".git",
  ".dart_tool",
  "build",
  "dist",
  "target",
  ".deno",
  ".data",
  "Pods",
  ".gradle",
  "ephemeral",
]);

/** Directories (as "/path", root as "/") that contain a file matching `want`, at most 4 levels deep. */
export function findDirs(root: string, want: (name: string) => boolean, depth = 4, rel = ""): string[] {
  const here = join(root, rel);
  const out: string[] = [];
  const entries = readdirSync(here, { withFileTypes: true });
  if (entries.some((e) => e.isFile() && want(e.name))) out.push("/" + rel.replaceAll("\\", "/"));
  if (depth > 0) {
    for (const e of entries) {
      if (e.isDirectory() && !SKIP.has(e.name)) out.push(...findDirs(root, want, depth - 1, join(rel, e.name)));
    }
  }
  return out.sort();
}

export function scan(root: string): Found {
  const dirs = (want: (n: string) => boolean) => findDirs(root, want);
  return {
    deno: dirs((n) => n === "deno.json" || n === "deno.jsonc" || n === "package.json"),
    docker: dirs((n) => n === "Dockerfile"),
    pub: dirs((n) => n === "pubspec.yaml"),
    cargo: dirs((n) => n === "Cargo.toml"),
  };
}

const q = (d: string) => (d === "/" ? "/" : d.replace(/\/$/, ""));

function block(ecosystem: string, dirs: string[], extra = ""): string {
  const dir = dirs.length === 1
    ? `    directory: "${q(dirs[0])}"`
    : `    directories:\n${dirs.map((d) => `      - "${q(d)}"`).join("\n")}`;
  return `  - package-ecosystem: ${ecosystem}
${dir}
    schedule:
      interval: weekly
      day: monday
    # Wait a week after a release before proposing it: most malicious or broken releases are pulled within days.
    cooldown:
      default-days: 7
    open-pull-requests-limit: 5
    labels: [dependencies]
    groups:
      ${ecosystem.replace("-", "_")}_minor_patch:
        update-types: [minor, patch]
${extra}`;
}

export function dependabotYaml(f: Found): string {
  const blocks = [
    block("github-actions", ["/"], ""),
    f.deno.length ? block("deno", f.deno) : "",
    f.docker.length ? block("docker", f.docker) : "",
    f.pub.length ? block("pub", f.pub) : "",
    f.cargo.length ? block("cargo", f.cargo) : "",
  ].filter(Boolean);
  return `# Generated by \`deno task security:sync\` from the folders that exist; re-run it after adding or removing an app.
# Updates arrive as grouped weekly pull requests, and CI must pass before you merge them. Using GitLab or wanting
# one tool for everything? See docs/DEVSECOPS.md for a Renovate alternative.
version: 2
updates:
${blocks.join("")}`;
}

if (import.meta.main) {
  const file = ".github/dependabot.yml";
  const wanted = dependabotYaml(scan("."));
  const current = existsSync(file) ? readFileSync(file, "utf8") : "";
  if (Deno.args.includes("--check")) {
    if (current !== wanted) {
      console.error(`${file} is out of date. Run: deno task security:sync`);
      Deno.exit(1);
    }
    console.log(`${file} is up to date.`);
  } else if (current === wanted) {
    console.log(`${file} is already up to date.`);
  } else {
    mkdirSync(".github", { recursive: true });
    writeFileSync(file, wanted);
    console.log(`Wrote ${file}.`);
  }
}
